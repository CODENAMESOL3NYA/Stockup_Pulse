"""
StockUp Pulse - Restocking Agent Orchestrator
Coordinates:
  - Document extraction
  - Deterministic forecasting
  - Budget-constrained planning with brand substitution
  - Evolus workflow & agent building blocks
  - Plain-language explanation writer
"""

from typing import Dict, Any, List, Optional
from stockup_pulse.adapters.amd_llm import amd_llm
from stockup_pulse.adapters.evolus import evolus_adapter
from stockup_pulse.forecast.forecaster import forecaster
from stockup_pulse.catalogue.matcher import matcher
from stockup_pulse.planning.optimizer import optimizer
from stockup_pulse.orders.manager import order_manager, PlanNotApprovedError

class RestockingAgent:
    def __init__(self):
        pass

    def run_pipeline(
        self,
        internal_catalogue: List[Dict[str, Any]],
        supplier_items: List[Dict[str, Any]],
        budget: float = 3000.0,
        planning_horizon_days: int = 14,
        allow_substitutions: bool = True
    ) -> Dict[str, Any]:
        """
        Runs the end-to-end restocking optimization pipeline.
        """
        # Step 1: Evolus Workflow trigger
        evolus_adapter.execute_workflow("restocking_optimization_flow", {"budget": budget})

        # Step 2: Match catalogue
        matched_catalogue = matcher.match_catalogue(internal_catalogue, supplier_items)

        # Step 3: Statistical forecasting for each item
        candidate_items = []
        for item in matched_catalogue:
            # Deterministic forecast based on sales history
            hist = item.get("sales_history", [3.0, 4.0, 2.0, 5.0, 3.5, 4.0, 6.0])
            lead_time = 2 if "makro" in item.get("supplier", "").lower() else 3
            current_stock = float(item.get("current_stock", 5.0))
            
            fc = forecaster.forecast_item(
                sales_history=hist,
                lead_time_days=lead_time,
                planning_horizon_days=planning_horizon_days,
                current_stock=current_stock
            )
            
            cand = {
                "product": item["product"],
                "pack_size": item["pack_size"],
                "supplier": item["supplier"],
                "supplier_price": item["supplier_price"],
                "unit_price": item["supplier_price"] / 24.0 if "24" in item["pack_size"] else item["supplier_price"],
                "our_price": item["our_price"],
                "recommended_qty": fc["recommended_qty"],
                "at_risk": fc["at_risk_before_delivery"],
                "is_out_of_stock": current_stock <= 0
            }
            candidate_items.append(cand)

        # Step 4: Deterministic optimization with brand substitution
        plan = optimizer.optimize_plan(
            candidate_items=candidate_items,
            budget=budget,
            planning_horizon_days=planning_horizon_days,
            allow_substitutions=allow_substitutions
        )

        # Step 5: Plain-language explanation generated by LLM (Reader/Writer only)
        explanation = amd_llm.write_plain_language_explanation(plan)
        plan["plain_language_explanation"] = explanation

        # Step 6: Evolus Agent action recorded
        evolus_adapter.run_agent_action("restocking_plan_generated", {"plan_version": plan["plan_version"]})

        return {
            "matched_catalogue": matched_catalogue,
            "plan": plan
        }

restocking_agent = RestockingAgent()
